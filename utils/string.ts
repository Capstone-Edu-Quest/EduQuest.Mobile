/** @format */

export const validateEmail = (email: string) => {
  const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
  return emailRegex.test(email);
};

export const onAddZeroToTime = (time: number): string => {
  return time < 10 ? `0${time}` : time.toString();
};

